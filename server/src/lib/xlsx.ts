import { deflateRawSync } from "node:zlib";

/**
 * A small Excel (.xlsx) writer without dependencies: an .xlsx file is a zip of XML parts.
 * Text cells are inline strings, numbers are numbers; the first row of each sheet is a bold
 * header with a filter and stays visible when scrolling (unless `plain`).
 */

export type Cell = string | number | null | undefined;
export interface SheetData {
  name: string;
  rows: Cell[][];
  /** Column widths in characters; worked out from the content when left out. */
  widths?: number[];
  /** No header row styling, filter or frozen first row (e.g. a key/value summary). */
  plain?: boolean;
}

const esc = (v: string) =>
  v.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!)
    // Characters XML 1.0 does not allow (matching control characters is the point here).
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, "");

function colName(i: number): string {
  let s = "";
  for (let n = i + 1; n > 0; n = Math.floor((n - 1) / 26)) s = String.fromCharCode(65 + ((n - 1) % 26)) + s;
  return s;
}

function sheetXml(sheet: SheetData): string {
  const width = Math.max(1, ...sheet.rows.map((r) => r.length));
  const widths = sheet.widths ?? Array.from({ length: width }, (_, c) =>
    Math.min(60, Math.max(8, ...sheet.rows.slice(0, 500).map((r) => String(r[c] ?? "").length + 2))));
  const rows = sheet.rows.map((row, r) => {
    const header = !sheet.plain && r === 0;
    const cells = row.map((v, c) => {
      const ref = `${colName(c)}${r + 1}`;
      const style = header ? ' s="1"' : "";
      if (v === null || v === undefined || v === "") return header ? `<c r="${ref}"${style}/>` : "";
      if (typeof v === "number" && Number.isFinite(v)) return `<c r="${ref}"${style}><v>${v}</v></c>`;
      return `<c r="${ref}"${style} t="inlineStr"><is><t xml:space="preserve">${esc(String(v)).slice(0, 32_000)}</t></is></c>`;
    }).join("");
    return `<row r="${r + 1}">${cells}</row>`;
  }).join("");
  const last = `${colName(width - 1)}${Math.max(1, sheet.rows.length)}`;
  const frozen = sheet.plain ? "" : '<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>';
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${frozen}<cols>${widths
    .map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`)
    .join("")}</cols><sheetData>${rows}</sheetData>${sheet.plain || sheet.rows.length < 2 ? "" : `<autoFilter ref="A1:${last}"/>`}</worksheet>`;
}

/** Sheet names: at most 31 characters, none of []:*?/\ and unique. */
function sheetNames(sheets: SheetData[]): string[] {
  const seen = new Set<string>();
  return sheets.map((s, i) => {
    let name = s.name.replace(/[[\]:*?/\\]/g, " ").trim().slice(0, 31) || `Sheet${i + 1}`;
    while (seen.has(name.toLowerCase())) name = `${name.slice(0, 28)} ${i + 1}`;
    seen.add(name.toLowerCase());
    return name;
  });
}

/** The range each sheet's filter covers, as Excel records it. */
function filterNames(sheets: SheetData[], names: string[]): string {
  const defs = sheets.flatMap((s, i) => {
    if (s.plain || s.rows.length < 2) return [];
    const width = Math.max(1, ...s.rows.map((r) => r.length));
    return [`<definedName name="_xlnm._FilterDatabase" localSheetId="${i}" hidden="1">'${esc(names[i]!).replace(/'/g, "''")}'!$A$1:$${colName(width - 1)}$${s.rows.length}</definedName>`];
  });
  return defs.length ? `<definedNames>${defs.join("")}</definedNames>` : "";
}

export function writeXlsx(sheets: SheetData[]): Buffer {
  const names = sheetNames(sheets);
  const files: [string, string][] = [
    ["[Content_Types].xml", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>${names
      .map((_, i) => `<Override PartName="/xl/worksheets/sheet${i + 1}.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>`)
      .join("")}</Types>`],
    ["_rels/.rels", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>`],
    ["xl/workbook.xml", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>${names
      .map((n, i) => `<sheet name="${esc(n)}" sheetId="${i + 1}" r:id="rId${i + 1}"/>`)
      .join("")}</sheets>${filterNames(sheets, names)}</workbook>`],
    ["xl/_rels/workbook.xml.rels", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">${names
      .map((_, i) => `<Relationship Id="rId${i + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet${i + 1}.xml"/>`)
      .join("")}<Relationship Id="rId${names.length + 1}" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>`],
    ["xl/styles.xml", `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><fonts count="2"><font><sz val="11"/><name val="Calibri"/></font><font><b/><sz val="11"/><name val="Calibri"/></font></fonts><fills count="3"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill><fill><patternFill patternType="solid"><fgColor rgb="FFE8EEF6"/><bgColor indexed="64"/></patternFill></fill></fills><borders count="1"><border><left/><right/><top/><bottom/><diagonal/></border></borders><cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs><cellXfs count="2"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/><xf numFmtId="0" fontId="1" fillId="2" borderId="0" xfId="0" applyFont="1" applyFill="1"/></cellXfs><cellStyles count="1"><cellStyle name="Normal" xfId="0" builtinId="0"/></cellStyles></styleSheet>`],
    ...sheets.map((s, i): [string, string] => [`xl/worksheets/sheet${i + 1}.xml`, sheetXml(s)]),
  ];
  return zip(files.map(([name, text]) => [name, Buffer.from(text, "utf8")]));
}

