/** "camera.monitoring_disabled" → "Monitoring turned off"; unknown codes → "Camera · monitoring disabled". */
export function auditLabel(action: string): string {
  if (LABELS[action]) return LABELS[action];
  const [area, what] = action.split(".");
  return what ? `${area!.charAt(0).toUpperCase()}${area!.slice(1).replace(/_/g, " ")} · ${what.replace(/_/g, " ")}` : action;
}

/** Whether the entry is a refusal or failure, shown in red. */
export const auditIsProblem = (action: string) => /failed|refused/.test(action);

